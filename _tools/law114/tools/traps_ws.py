def pages(pg):
    ns = [int(n) for n in re.findall(r'\d+', pg or '')]
    if '–' in (pg or '') and len(ns) == 2: return set(range(ns[0], ns[1] + 1))
    return set(ns)

def txt(b):
    if b['t'] == 'list': return b.get('lead', '') + ' ' + ' / '.join(b['items'])
    if b['t'] == 'q' and 'parts' in b: return ' '.join(([b['pre']] if b.get('pre') else []) + b['parts'] + ([b['post']] if b.get('post') else []))
    return b.get('x', '')

